"""
Обновления NASLUX: версии, что изменилось и где это теперь.

Список ведётся здесь, в коде, а не в базе: заметки к версии выезжают
вместе с самой версией -- не бывает, что на сайте уже новое, а рассказ о
нём ещё не написан. Окно «Что нового» всплывает один раз после обновления
тем, кто пользовался сервисом раньше (новичку рассказывать о переменах не
к чему); закрыл -- сервер запоминает версию, и на другом устройстве окно
уже не появится. Все версии -- на странице /updates.
"""
from __future__ import annotations

import datetime as dt
from dataclasses import dataclass, field

KIND_LABELS = {"new": "Новое", "better": "Стало удобнее", "fixed": "Исправлено", "moved": "Переехало"}


@dataclass(frozen=True)
class Change:
    title: str
    text: str
    kind: str = "new"
    where: str = ""               # где это теперь -- словами человека, а не адресом

    @property
    def kind_label(self) -> str:
        return KIND_LABELS[self.kind]

    def as_dict(self) -> dict:
        return {"title": self.title, "text": self.text, "kind": self.kind, "kindLabel": self.kind_label,
                "where": self.where}


@dataclass(frozen=True)
class Release:
    version: str
    date: dt.date
    title: str
    summary: str
    changes: tuple[Change, ...] = field(default_factory=tuple)

    @property
    def anchor(self) -> str:
        return "v" + self.version.replace(".", "-")

    @property
    def released_at(self) -> float:
        return dt.datetime.combine(self.date, dt.time(0)).timestamp()


def version_key(version: str) -> tuple[int, ...]:
    try:
        return tuple(int(x) for x in (version or "0").split("."))
    except ValueError:
        return (0,)


