CURRENT = RELEASES[0]
WINDOW_ITEMS = 5


def unseen(seen: str, since: float) -> list[Release]:
    """Версии, о которых человеку ещё не рассказали: новее просмотренной и
    вышедшие после того, как он пришёл (новичку -- ничего)."""
    return [r for r in RELEASES
            if version_key(r.version) > version_key(seen) and r.released_at > since]


def notice(seen: str, since: float) -> dict | None:
    """Окно «Что нового»: не больше пяти пунктов -- подробности на /updates."""
    pending = unseen(seen, since)
    if not pending:
        return None
    changes = [c.as_dict() for r in pending for c in r.changes][:WINDOW_ITEMS]
    if len(pending) > 1:
        label, title = f"Обновления {pending[-1].version}–{pending[0].version}", "Что нового в NASLUX"
    else:
        label, title = f"Обновление {pending[0].version}", f"Что нового: {pending[0].title.lower()}"
    return {"version": CURRENT.version, "label": label, "title": title, "changes": changes,
            "more": max(0, sum(len(r.changes) for r in pending) - len(changes))}
